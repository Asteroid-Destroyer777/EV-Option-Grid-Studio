// One rule for the ranking, selected-site report and exported report.
export function investmentVerdict({npv,lowNpv,payback}) {
  if(npv<=0)return 'При спросе 100% ЧПС неположительна: пересмотрите параметры до инвестиционного решения.';
  if(lowNpv<=0)return 'При спросе 100% ЧПС положительна, при 50% — неположительна. Инвестиционное решение — после подтверждения спроса и параметров площадки.';
  if(payback==null)return 'ЧПС положительна при спросе 50% и 100%, но дисконтированная окупаемость в горизонте не достигнута. Требуется проверка параметров.';
  return 'Сценарии спроса 50% и 100% проходят финансовый фильтр. Следующий шаг — проверка исходных данных и площадки в пилоте.';
}
